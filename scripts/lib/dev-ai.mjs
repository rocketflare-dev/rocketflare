/**
 * The local Workers AI switch, kept OUT of every tracked file. Workers AI has no local emulation:
 * `wrangler dev` proxies the `[ai]` binding to Cloudflare, which needs `wrangler login`. A machine
 * that wants to run without one sets `DEV_WORKERS_AI=off` — in the shell or in
 * `apps/web/.dev.vars` (git-ignored; the shell wins, as for `DEV_API_PORT`) — and every local
 * `wrangler dev` launch (`pnpm dev`, `pnpm dev:api`, `pnpm dev:tunnel`) then runs from a
 * generated, git-ignored copy of `wrangler.toml` with the `[ai]` block commented out:
 * `apps/web/.wrangler.offline.toml`, written fresh at every launch.
 *
 * Why a generated copy and not `wrangler dev --local`: `--local` keeps an `env.AI` stub that
 * throws when called, so `services/ai/resolve.ts` would see a binding and answer 500 instead of
 * falling through to keys and tenant providers (and 503). The copy gives the Worker no `AI` at
 * all — the same runtime the commented-out block used to — while the two tracked tomls and the
 * generated `worker-configuration.d.ts` stay identical online or offline. It sits beside
 * `wrangler.toml` because wrangler resolves `main`, `[assets]` and `.dev.vars` relative to the
 * config file. `pnpm bootstrap --offline` / `--online` write and clear the key. Types:
 * `dev-ai.d.mts`.
 */
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { aiBlockState, readDevVars, toggleAiBlock } from './bootstrap-lib.mjs'

export const DEV_WORKERS_AI = 'DEV_WORKERS_AI'
export const OFFLINE_CONFIG = '.wrangler.offline.toml'

const OFF = new Set(['off', 'false', '0', 'no'])

/**
 * Pure: `'off'` when `DEV_WORKERS_AI` (shell first, then `.dev.vars`) says off, else `'on'`. A
 * blank value counts as unset, so `DEV_WORKERS_AI=` in `.dev.vars` is "on".
 */
export function devWorkersAiMode(env = {}, devVars = {}) {
  for (const source of [env, devVars]) {
    const value = source?.[DEV_WORKERS_AI]
    if (value !== undefined && String(value).trim() !== '') {
      return OFF.has(String(value).trim().toLowerCase()) ? 'off' : 'on'
    }
  }
  return 'on'
}

const HEADER = [
  '# GENERATED by scripts/lib/dev-ai.mjs at every local `wrangler dev` launch while',
  '# DEV_WORKERS_AI=off (shell or apps/web/.dev.vars): wrangler.toml with the [ai] block commented',
  '# out. Git-ignored; never edit it, never deploy from it. Delete the key to use Workers AI again.',
  '',
]

/** Pure: the offline config text for a `wrangler.toml` text — `[ai]` commented out, a header. */
export function offlineConfigText(tomlText) {
  return `${HEADER.join('\n')}${toggleAiBlock(tomlText, 'off')}`
}

/**
 * The arguments every local `wrangler dev` launch prepends, for the web app at `webDir`: offline,
 * `['--config', OFFLINE_CONFIG]` after (re)writing that file; online, `[]` after deleting a stale
 * one. `mode` and a `note` (one line, or null) come back for the caller to print.
 */
export function wranglerDevConfigArgs({ webDir, env = process.env, devVars } = {}) {
  const devVarsFile = path.join(webDir, '.dev.vars')
  const values =
    devVars ?? (existsSync(devVarsFile) ? readDevVars(readFileSync(devVarsFile, 'utf8')) : {})
  const mode = devWorkersAiMode(env, values)
  const offline = path.join(webDir, OFFLINE_CONFIG)
  const toml = readFileSync(path.join(webDir, 'wrangler.toml'), 'utf8')
  // A copy from before the switch moved may still have the block commented out in git.
  const legacy =
    aiBlockState(toml) === 'off'
      ? '[ai] is commented out in wrangler.toml itself — run `pnpm bootstrap --offline` (or --online) to restore the tomls and keep the switch in .dev.vars'
      : null
  if (mode === 'off') {
    writeFileSync(offline, offlineConfigText(toml))
    return {
      mode,
      args: ['--config', OFFLINE_CONFIG],
      note: legacy ?? `Workers AI off (${DEV_WORKERS_AI}=off) — running from ${OFFLINE_CONFIG}`,
    }
  }
  rmSync(offline, { force: true })
  return { mode, args: [], note: legacy }
}
